"""
Create a canonical summary of the multi-resolution counting experiments.

This script does not run any models. It reads the result artifacts produced by
the task scripts and writes:

    reports/results_summary.csv
    reports/results_summary.md
    reports/results_summary.png

Run from the CLIP-EBC directory:

    python summarize_results.py
"""

from __future__ import annotations

import csv
import re
from pathlib import Path
from typing import Optional

import matplotlib.pyplot as plt


ROOT = Path(__file__).resolve().parent
REPORT_DIR = ROOT / "reports"


def read_metric_summary(path: Path) -> Optional[tuple[float, float, int | None]]:
    if not path.exists():
        return None

    text = path.read_text()
    mae_match = re.search(r"MAE:\s*([0-9.]+)", text)
    rmse_match = re.search(r"RMSE:\s*([0-9.]+)", text)
    n_match = re.search(r"(?:Num images|N):\s*([0-9]+)", text)
    if not mae_match or not rmse_match:
        return None

    n = int(n_match.group(1)) if n_match else None
    return float(mae_match.group(1)), float(rmse_match.group(1)), n


def add_summary_row(rows: list[dict[str, object]], task: str, experiment: str, path: Path, note: str) -> None:
    metrics = read_metric_summary(path)
    if metrics is None:
        return

    mae, rmse, n = metrics
    rows.append(
        {
            "task": task,
            "experiment": experiment,
            "mae": round(mae, 4),
            "rmse": round(rmse, 4),
            "n": n if n is not None else "",
            "source": str(path.relative_to(ROOT)),
            "note": note,
        }
    )


def read_comparison_csv(
    path: Path,
    task: str,
    note: str,
    experiment_filter: Optional[set[str]] = None,
) -> list[dict[str, object]]:
    if not path.exists():
        return []

    rows: list[dict[str, object]] = []
    with path.open(newline="") as f:
        for row in csv.DictReader(f):
            if experiment_filter is not None and row["model"] not in experiment_filter:
                continue
            rows.append(
                {
                    "task": task,
                    "experiment": row["model"],
                    "mae": round(float(row["mae"]), 4),
                    "rmse": round(float(row["rmse"]), 4),
                    "n": 500,
                    "source": str(path.relative_to(ROOT)),
                    "note": note,
                }
            )
    return rows


def collect_rows() -> list[dict[str, object]]:
    rows: list[dict[str, object]] = []

    add_summary_row(
        rows,
        "Task 3",
        "Teacher CLIP-EBC @ 1x original",
        ROOT / "task3_outputs" / "nwpu_val_summary.txt",
        "Baseline NWPU validation result.",
    )

    for factor in ("2p0", "4p0"):
        label = factor.replace("p0", "x").replace("1x", "1x original")
        add_summary_row(
            rows,
            "Task 4",
            f"Teacher CLIP-EBC @ {label}",
            ROOT / "task4_outputs_downscale" / f"scale_{factor}" / "summary.txt",
            "Same teacher evaluated after input downscaling; GT counts unchanged.",
        )

    student_runs = [
        ("Task 5", "Fixed 2x student, 50 epochs, lr=1e-5", "e50_lr1e-5_ds2"),
        ("Task 5", "Fixed 4x student, 50 epochs, lr=3e-5", "e50_lr3e-5_ds4"),
    ]
    for task, label, folder in student_runs:
        rows.extend(
            read_comparison_csv(
                ROOT / "student_eval_outputs" / folder / "comparison.csv",
                task,
                label,
                experiment_filter={"Student @ 2x (distilled)", "Student @ 4x (distilled)"},
            )
        )

    add_summary_row(
        rows,
        "SR",
        "Teacher @ bicubic SR (2x->1x)",
        ROOT / "sr_eval_outputs" / "ds2" / "teacher_bicubic_sr" / "summary.txt",
        "Teacher evaluated on 2x downscaled inputs upsampled back to 1x with bicubic interpolation.",
    )

    return rows


def write_csv(rows: list[dict[str, object]], path: Path) -> None:
    fieldnames = ["task", "experiment", "mae", "rmse", "n", "source", "note"]
    with path.open("w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(rows)


def write_markdown(rows: list[dict[str, object]], path: Path) -> None:
    lines = [
        "# Multi-Resolution Counting Results Summary",
        "",
        "Generated by `python summarize_results.py` from existing result artifacts.",
        "",
        "| Task | Experiment | MAE | RMSE | N | Source | Note |",
        "|---|---:|---:|---:|---:|---|---|",
    ]

    for row in rows:
        lines.append(
            "| {task} | {experiment} | {mae:.4f} | {rmse:.4f} | {n} | `{source}` | {note} |".format(
                **row
            )
        )

    lines.extend(
        [
            "",
            "## Excluded Experiments",
            "",
            "Scale jitter, Real-ESRGAN, and real-world zoom-pair outputs are intentionally excluded from this core comparison.",
        ]
    )
    path.write_text("\n".join(lines) + "\n")


def write_plot(rows: list[dict[str, object]], path: Path) -> None:
    selected_labels = [
        "Teacher CLIP-EBC @ 1x original",
        "Teacher CLIP-EBC @ 2x",
        "Teacher CLIP-EBC @ 4x",
        "Student @ 2x (distilled)",
        "Student @ 4x (distilled)",
        "Teacher @ bicubic SR (2x->1x)",
    ]

    selected = []
    seen = set()
    for row in rows:
        label = str(row["experiment"]).replace("2x\u21921x", "2x->1x")
        if label in selected_labels and label not in seen:
            selected.append({**row, "experiment": label})
            seen.add(label)

    if not selected:
        return

    labels = [str(row["experiment"]) for row in selected]
    mae = [float(row["mae"]) for row in selected]
    rmse = [float(row["rmse"]) for row in selected]

    x = range(len(selected))
    width = 0.38

    plt.figure(figsize=(13, 6))
    plt.bar([i - width / 2 for i in x], mae, width=width, label="MAE", color="#377eb8")
    plt.bar([i + width / 2 for i in x], rmse, width=width, label="RMSE", color="#e41a1c")
    plt.xticks(list(x), labels, rotation=30, ha="right")
    plt.ylabel("Count error")
    plt.title("NWPU validation error across resolution experiments")
    plt.legend()
    plt.tight_layout()
    plt.savefig(path, dpi=180)
    plt.close()


def main() -> None:
    REPORT_DIR.mkdir(exist_ok=True)
    rows = collect_rows()
    if not rows:
        raise SystemExit("No result artifacts found. Run the task evaluation scripts first.")

    csv_path = REPORT_DIR / "results_summary.csv"
    md_path = REPORT_DIR / "results_summary.md"
    plot_path = REPORT_DIR / "results_summary.png"

    write_csv(rows, csv_path)
    write_markdown(rows, md_path)
    write_plot(rows, plot_path)

    print(f"Wrote {csv_path.relative_to(ROOT)}")
    print(f"Wrote {md_path.relative_to(ROOT)}")
    print(f"Wrote {plot_path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
